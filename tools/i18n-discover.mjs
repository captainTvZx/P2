for (const [lang, index] of [['en', 0], ['tr', 1]]) {
  const file = join(ROOT, 'crates/p2-i18n/locales', lang + '.json')
  const dict = JSON.parse(readFileSync(file, 'utf8'))
  let added = 0, changed = 0
  for (const [key, pair] of Object.entries(TEXT)) {
    if (!(key in dict)) added++
    else if (dict[key] !== pair[index]) changed++
    dict[key] = pair[index]
  }
  const sorted = Object.fromEntries(Object.keys(dict).sort().map(k => [k, dict[k]]))
  writeFileSync(file, JSON.stringify(sorted, null, 1) + '\n')
  console.log(`${lang}: +${added} yeni, ${changed} güncellendi (${Object.keys(sorted).length} anahtar)`)
}
